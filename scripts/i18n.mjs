import { mkdir, readFile, writeFile } from "node:fs/promises";
import { realpathSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import {
  LOCALE_PATTERN,
  SOURCE_LOCALE,
  listLocales,
  readLocale,
  sourceHash,
  unformattedFiles,
  writeLocale,
} from "./i18n-catalog.mjs";

const root = new URL("../", import.meta.url);
const generatedDir = new URL("src/i18n/generated/", root);
const typesPath = new URL("messageParams.ts", generatedDir);
const PLURAL_CATEGORIES = ["zero", "one", "two", "few", "many", "other"];

const forms = (message) =>
  typeof message === "string" ? [message] : Object.values(message);
export const placeholders = (message) =>
  [
    ...new Set(
      forms(message).flatMap((text) =>
        [...text.matchAll(/\{(\w+)\}/g)].map((match) => match[1])
      )
    ),
  ].sort();

function validateMessage(message, key) {
  if (typeof message !== "string") {
    if (
      !message ||
      Array.isArray(message) ||
      typeof message !== "object" ||
      typeof message.other !== "string"
    ) {
      throw new Error(`${key}: plural messages require an other form`);
    }
    for (const category of Object.keys(message)) {
      if (!PLURAL_CATEGORIES.includes(category)) {
        throw new Error(`${key}: invalid plural category ${category}`);
      }
    }
  }
  for (const text of forms(message)) {
    if (typeof text !== "string" || !text.trim())
      throw new Error(`${key}: empty/non-string message`);
    if (/[{}]/.test(text.replace(/\{\w+\}/g, "")))
      throw new Error(`${key}: only {name} placeholders are supported`);
  }
}

export async function readSource() {
  const source = await readLocale(root, SOURCE_LOCALE);
  for (const [key, entry] of Object.entries(source)) {
    if (!/^[a-zA-Z][\w.-]+$/.test(key) || !entry.description?.trim())
      throw new Error(`${key}: stable ID and description required`);
    validateMessage(entry.message, key);
    // "keywords": search terms people type, never shown. Translations are
    // matched together with the English, so English searches keep working.
    if (entry.kind !== undefined && entry.kind !== "keywords")
      throw new Error(`${key}: unknown kind ${JSON.stringify(entry.kind)}`);
    if (entry.kind === "keywords" && typeof entry.message !== "string")
      throw new Error(`${key}: keyword entries can't be plural`);
  }
  return source;
}

function renderTypes(source) {
  return (
    "// Generated by node scripts/i18n.mjs types from src/i18n/locales/en. Do not edit.\n" +
    "export type MessageParams = {\n" +
    Object.keys(source)
      .sort()
      .map((key) => {
        const { message } = source[key];
        const names = placeholders(message);
        if (typeof message !== "string" && !names.includes("count"))
          names.push("count");
        const params = names.length
          ? `{ ${names
              .map(
                (name) =>
                  `${JSON.stringify(name)}: ${
                    name === "count" ? "number" : "string | number"
                  }`
              )
              .join("; ")} }`
          : "never";
        return `  ${JSON.stringify(key)}: ${params};`;
      })
      .join("\n") +
    "\n};\n"
  );
}

/** Write generated types only when they change, so watchers don't loop. */
export async function writeTypes(source) {
  const generated = renderTypes(source ?? (await readSource()));
  let current = null;
  try {
    current = await readFile(typesPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (current === generated) return false;
  await mkdir(generatedDir, { recursive: true });
  await writeFile(typesPath, generated);
  return true;
}

const requireTarget = (locale) => {
  if (!locale || locale === SOURCE_LOCALE || !LOCALE_PATTERN.test(locale))
    throw new Error("Provide a target locale, e.g. zh-Hans");
};

/**
 * Why a translated message can't ship for this source entry, or null. Shared by
 * `check` and the translation runner so both accept exactly the same output.
 */
export function translationProblem(locale, sourceEntry, message) {
  try {
    validateMessage(message, "message");
  } catch (error) {
    return error.message.replace(/^message: /, "");
  }
  if ((typeof message === "string") !== (typeof sourceEntry.message === "string"))
    return typeof sourceEntry.message === "string"
      ? "expected a plain string, got plural forms"
      : "expected plural forms, got a plain string";
  if (typeof message !== "string") {
    // A translated plural must cover exactly what that language selects.
    const needed = new Intl.PluralRules(locale).resolvedOptions().pluralCategories;
    for (const category of needed)
      if (typeof message[category] !== "string")
        return `missing plural form ${category}`;
  }
  const expected = placeholders(sourceEntry.message);
  if (typeof message === "string") {
    if (JSON.stringify(placeholders(message)) !== JSON.stringify(expected))
      return `placeholder mismatch: expected ${JSON.stringify(expected)}, got ${JSON.stringify(
        placeholders(message)
      )}`;
    return null;
  }
  // Plural forms may leave out {count} (English "Move task to" vs "Move
  // {count} tasks to"); every other placeholder must appear in every form.
  const required = expected.filter((name) => name !== "count");
  for (const form of forms(message)) {
    const used = placeholders(form);
    const extra = used.filter((name) => !expected.includes(name));
    const missing = required.filter((name) => !used.includes(name));
    if (extra.length || missing.length)
      return `placeholder mismatch: expected ${JSON.stringify(expected)}${
        missing.length ? `, missing ${JSON.stringify(missing)}` : ""
      }${extra.length ? `, unknown ${JSON.stringify(extra)}` : ""}`;
  }
  return null;
}

/**
 * Current translations must be valid. Stale ones (English or context changed
 * since) are reported, not fatal: English edits must not break every build
 * while the translation PR catches up. They keep showing if they still fit
 * the new English, and fall back to English if they don't (see runtimeCatalog).
 */
function checkTranslation(locale, source, catalog) {
  const stale = [];
  for (const [key, entry] of Object.entries(catalog)) {
    if (!source[key]) throw new Error(`${locale}: unknown message ${key}`);
    if (entry.sourceHash !== sourceHash(source[key])) {
      stale.push(key);
      continue;
    }
    const problem = translationProblem(locale, source[key], entry.message);
    if (problem) throw new Error(`${locale}: ${key}: ${problem}`);
  }
  return stale;
}

/** What ships for a locale: every translation that fits the current English. */
export function runtimeCatalog(locale, source, catalog) {
  return Object.fromEntries(
    Object.keys(catalog)
      .sort()
      .filter((key) => source[key] && !translationProblem(locale, source[key], catalog[key].message))
      .map((key) => [key, catalog[key].message])
  );
}

/** Source entries a locale lacks or whose English/context changed since translation. */
export function pendingEntries(source, translated) {
  return Object.keys(source)
    .sort()
    .filter((key) => translated[key]?.sourceHash !== sourceHash(source[key]))
    .map((key) => ({ key, ...source[key], sourceHash: sourceHash(source[key]) }));
}

/**
 * Marks translations a person wrote or edited as current: an entry with no
 * hash, or whose message differs from `base` (the same locale before the
 * change), gets the current English hash. Contributors edit only `message`;
 * this records that they translated against today's English, so the runner
 * won't redraft their work. Untouched stale entries stay stale.
 */
export function stampEntries(source, catalog, base = {}) {
  const stamped = [];
  for (const [key, entry] of Object.entries(catalog)) {
    if (!source[key]) continue;
    const edited =
      !entry.sourceHash ||
      JSON.stringify(entry.message) !== JSON.stringify(base[key]?.message);
    const hash = sourceHash(source[key]);
    if (edited && entry.sourceHash !== hash) {
      catalog[key] = { message: entry.message, sourceHash: hash };
      stamped.push(key);
    }
  }
  return stamped;
}

const git = (args) =>
  execFileSync("git", args, {
    cwd: fileURLToPath(root),
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    maxBuffer: 256 * 1024 * 1024,
  });

/** A locale as it was at `commit`, read from Git without touching the tree. */
function readLocaleAt(commit, locale) {
  const dir = `src/i18n/locales/${locale}/`;
  let names;
  try {
    names = git(["ls-tree", "--name-only", commit, dir]).split("\n").filter(Boolean);
  } catch {
    return {};
  }
  const catalog = {};
  for (const path of names.filter((name) => name.endsWith(".json")))
    Object.assign(catalog, JSON.parse(git(["show", `${commit}:${path}`])));
  return catalog;
}

export async function run(command, locale, options = {}) {
  if (command === "format") {
    for (const name of await listLocales(root))
      await writeLocale(root, name, await readLocale(root, name, { missingOk: true }));
    return "Formatted locale catalogs";
  }

  const source = await readSource();

  if (command === "types") {
    await writeTypes(source);
    return "Generated message parameter types";
  }

  if (command === "pending") {
    requireTarget(locale);
    const translated = await readLocale(root, locale, { missingOk: true });
    return JSON.stringify(
      {
        locale,
        entries: Object.fromEntries(
          pendingEntries(source, translated).map(({ key, ...entry }) => [key, entry])
        ),
      },
      null,
      2
    );
  }

  if (command === "stamp") {
    if (locale) requireTarget(locale);
    const baseRef = options.base ?? "origin/main";
    const commit = git(["merge-base", baseRef, "HEAD"]).trim();
    const locales = locale
      ? [locale]
      : (await listLocales(root)).filter((name) => name !== SOURCE_LOCALE);
    const lines = [];
    for (const name of locales) {
      const catalog = await readLocale(root, name, { missingOk: true });
      const stamped = stampEntries(source, catalog, readLocaleAt(commit, name));
      if (!stamped.length) continue;
      await writeLocale(root, name, catalog);
      lines.push(`${name}: marked ${stamped.length} edited translation(s) current`);
    }
    return lines.length
      ? lines.join("\n")
      : `No edited translations to stamp (compared with ${baseRef})`;
  }

  if (command === "prune") {
    // English is synced from the app repository; a message it deleted leaves
    // translations that `check` rejects as unknown. Drop them.
    const lines = [];
    for (const name of (await listLocales(root)).filter((n) => n !== SOURCE_LOCALE)) {
      const catalog = await readLocale(root, name, { missingOk: true });
      const removed = Object.keys(catalog).filter((key) => !source[key]);
      if (!removed.length) continue;
      for (const key of removed) delete catalog[key];
      await writeLocale(root, name, catalog);
      lines.push(`${name}: removed ${removed.length} translation(s) of deleted messages`);
    }
    return lines.length ? lines.join("\n") : "No translations of deleted messages";
  }

  if (command !== "check")
    throw new Error(
      "Usage: node scripts/i18n.mjs types|check|format|pending|stamp|prune [locale] [--base ref]"
    );

  const locales = await listLocales(root);
  const unformatted = (
    await Promise.all(locales.map((name) => unformattedFiles(root, name)))
  ).flat();
  if (unformatted.length)
    throw new Error(
      `Catalog files are not in canonical order: ${unformatted.join(", ")}. Run pnpm i18n:format`
    );
  const notes = [];
  for (const name of locales.filter((name) => name !== SOURCE_LOCALE)) {
    const catalog = await readLocale(root, name, { missingOk: true });
    const stale = checkTranslation(name, source, catalog);
    if (locale === name) {
      // Release gate for a locale: complete and current.
      if (Object.keys(source).some((key) => !catalog[key]))
        throw new Error(`${name}: incomplete catalog`);
      if (stale.length)
        throw new Error(`${name}: stale translation ${stale.join(", ")}`);
    } else if (stale.length) {
      notes.push(`${name}: ${stale.length} stale (run pnpm i18n:translate ${name})`);
    }
  }
  if (locale && !locales.includes(locale)) throw new Error(`Missing catalog ${locale}`);
  return [
    `Localization checks passed (${Object.keys(source).length} English messages)`,
    ...notes,
  ].join("\n");
}

if (
  process.argv[1] &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
) {
  // No top-level await: vitest bundles its config (which loads this module
  // through the Vite plugin) as CommonJS.
  const args = process.argv.slice(3);
  const baseAt = args.indexOf("--base");
  const options = baseAt === -1 ? {} : { base: args[baseAt + 1] };
  if (baseAt !== -1) args.splice(baseAt, 2);
  run(process.argv[2], args[0], options).then(
    (message) => console.log(message),
    (error) => {
      console.error(error.message);
      process.exitCode = 1;
    }
  );
}
